type YargsError = Error & { yargsMessage?: string };
export interface ConsumedArgvResult {
  yargs: Yargs.Argv;
  argv: Extract<Yargs.Argv["argv"], { $0: string }>;
}
export interface ConsumeArgvOptions {
  /**
   * If set to `true`, the consumer function will return a promise.
   * @default false
   */
  async?: boolean;
  /**
   * If set to `true`, any error occurred while parsing the argv will be thrown.
   * Otherwise, will ignore the error and just log the error message.
   * @default false
   */
  throwError?: boolean;
}

const moduleExtensions = ['js'];
const projectMetadata = (getGlob('$__metadata__$') || {}) as Partial<ProjectMetadata>;

